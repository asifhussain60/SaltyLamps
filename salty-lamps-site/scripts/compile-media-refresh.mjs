// Compile reviewed media into an inspectable, repeatable migration. Never contacts D1.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'data/media-refresh.json')))
const assignments = JSON.parse(fs.readFileSync(path.join(root, 'data/media-refresh-assignments.json')))
const assets = new Map(manifest.assets.map(a => [a.id, a]))
const q = s => "'" + String(s).replaceAll("'", "''") + "'"
const assetPath = id => {
  const a = assets.get(id)
  if (!a || a.status !== 'reviewed' || !fs.existsSync(path.join(root, 'public', a.output))) throw new Error(`Missing reviewed asset: ${id}`)
  return a.output
}
const sql = ['-- Generated by scripts/compile-media-refresh.mjs. Preserve original media for rollback.',
  '-- Apply 009-option-images.sql first. Uses product + SKU + option label; database numeric IDs can differ.',
  'CREATE TABLE IF NOT EXISTS media_refresh_runs (id TEXT PRIMARY KEY, applied_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);']
const pending = `NOT EXISTS (SELECT 1 FROM media_refresh_runs WHERE id=${q(assignments.version)})`
const snapshotPath = path.join(root, 'src/content/content-snapshot.json')
const snapshot = JSON.parse(fs.readFileSync(snapshotPath))
const optionKey = (productId, sku, label) => JSON.stringify([productId, sku, label || ''])
const optionAssets = new Map()
for (const p of assignments.products) for (const o of p.options) {
  const key = optionKey(p.productId, o.sku, o.label)
  if (optionAssets.has(key)) throw new Error(`Duplicate option: ${key}`)
  optionAssets.set(key, assetPath(o.asset))
}
for (const p of snapshot.products) {
  if (!optionAssets.has(optionKey(p.productId, p.sku, p.variantLabel))) throw new Error(`Unmapped catalogue option: ${p.name}`)
}
if (optionAssets.size !== snapshot.products.length) throw new Error('Assignment count differs from catalogue')
// Abort an incomplete first application before any catalogue changes. The
// migration runner provides the transaction; replays leave later owner edits alone.
sql.push('CREATE TABLE IF NOT EXISTS media_refresh_guard (valid INTEGER CHECK(valid=1));')
for (const p of assignments.products) for (const o of p.options) {
  sql.push(`INSERT INTO media_refresh_guard(valid) SELECT CASE WHEN (SELECT COUNT(*) FROM skus WHERE product_id=${q(p.productId)} AND sku=${q(o.sku)} AND variant_label=${q(o.label)})=1 THEN 1 ELSE 0 END WHERE ${pending};`)
}
sql.push('DELETE FROM media_refresh_guard;')
for (const p of assignments.products) {
  const cover = assetPath(p.cover)
  sql.push(`UPDATE products SET image=${q(cover)} WHERE id=${q(p.productId)} AND ${pending};`)
  sql.push(`INSERT INTO product_images (product_id, key, path, sort_order) SELECT ${q(p.productId)}, '', ${q(cover)}, -100 WHERE EXISTS (SELECT 1 FROM products WHERE id=${q(p.productId)}) AND NOT EXISTS (SELECT 1 FROM product_images WHERE product_id=${q(p.productId)} AND path=${q(cover)}) AND ${pending};`)
  for (const o of p.options || []) {
    const output = assetPath(o.asset)
    sql.push(`INSERT INTO product_images (product_id, key, path, sort_order) SELECT ${q(p.productId)}, '', ${q(output)}, 100 WHERE EXISTS (SELECT 1 FROM products WHERE id=${q(p.productId)}) AND NOT EXISTS (SELECT 1 FROM product_images WHERE product_id=${q(p.productId)} AND path=${q(output)}) AND ${pending};`)
    sql.push(`INSERT INTO sku_images (sku_id, image_id) SELECT s.id, (SELECT MIN(id) FROM product_images WHERE product_id=s.product_id AND path=${q(output)}) FROM skus s WHERE s.product_id=${q(p.productId)} AND s.sku=${q(o.sku)} AND s.variant_label=${q(o.label)} AND ${pending} ON CONFLICT(sku_id) DO UPDATE SET image_id=excluded.image_id;`)
  }
}
for (const replacement of assignments.replacements || []) {
  const output = assetPath(replacement.asset)
  for (const [table, column] of [['products','image'],['product_images','path'],['categories','image'],['collections','hero_poster'],['collections','background'],['collection_sections','image'],['theme_images','src']]) {
    sql.push(`UPDATE ${table} SET ${column}=${q(output)} WHERE ${column}=${q(replacement.source)} AND ${pending};`)
  }
}
sql.push(`INSERT OR IGNORE INTO media_refresh_runs(id) VALUES (${q(assignments.version)});`)
const output = path.join(root, 'd1/migrations/010-lighter-catalogue.sql')
fs.writeFileSync(output, sql.join('\n') + '\n')
const replacements = Object.fromEntries(assignments.replacements.map(r => [r.source, assetPath(r.asset)]))
fs.writeFileSync(path.join(root, 'src/content/media-map.mjs'), `// Generated from the reviewed media manifest.\nexport const mediaReplacements = ${JSON.stringify(replacements, null, 2)}\nexport const resolveMedia = value => mediaReplacements[value] || value\n`)
const replace = value => typeof value === 'string' ? (replacements[value] || value)
  : Array.isArray(value) ? value.map(replace)
  : value && typeof value === 'object' ? Object.fromEntries(Object.entries(value).map(([k,v]) => [k,replace(v)])) : value
const refreshed = replace(snapshot)
for (const p of refreshed.products) {
  const selected = optionAssets.get(optionKey(p.productId, p.sku, p.variantLabel))
  const familyPaths = new Set(assignments.products.find(a => a.productId === p.productId).options.map(o => assetPath(o.asset)))
  p.images = [...new Set([selected, ...(p.images || []).filter(src => !familyPaths.has(src))])]
  p.image = selected
  p.imageId = null // D1 assigns gallery identities at migration time, never invent them in the fallback snapshot.
  p.hasOptionImage = true
}
fs.writeFileSync(snapshotPath, JSON.stringify(refreshed, null, 2) + '\n')
console.log(`Compiled ${assignments.products.length} products and ${assignments.replacements?.length || 0} supporting references`)
